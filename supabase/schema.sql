-- 1. 历史记录表
create table if not exists name_history (
  id               bigint generated by default as identity primary key,
  user_requirement text        not null,          -- 用户的起名需求
  name_result      text        not null,          -- 模型生成的完整方案
  model_name       text        not null,          -- 实际调用的模型
  created_at       timestamptz not null default now()
);

-- 2. 按时间倒序查询的索引（历史列表就靠它）
create index if not exists idx_name_history_created_at
  on name_history (created_at desc);

-- 3. 开启行级安全
alter table name_history enable row level security;

-- ============================================================
-- 4-a. 课堂调试用：允许匿名读写
--      （anon key 是"公开钥匙"，能放进前端；真正的门是 RLS 策略）
-- ============================================================
drop policy if exists "anon can read history"   on name_history;
drop policy if exists "anon can insert history" on name_history;

create policy "anon can read history"
  on name_history for select
  to anon
  using (true);

create policy "anon can insert history"
  on name_history for insert
  to anon
  with check (true);

